#!/usr/bin/env python3.12
"""Convert preserved title PNGs to read-only planar data, using AGK's art mapping."""
import argparse
import hashlib
import os
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / "game/art"
NAMES = ("graveyard", "nebula", "foundry", "citadel")
KIT = Path(os.environ.get("AGK_KIT", str(Path.home() / "Code/amiga/amiga-game-kit")))
sys.path.insert(0, str(KIT / "harness"))
from agk.art import Asset, parse_palette


def title_words():
    palette = parse_palette(str(ART / "palette.txt"))
    frames = []
    for name in NAMES:
        asset = Asset(name, {"source": name + ".png", "kind": "bitmap", "depth": 4},
                      str(ART), palette, 4)
        if (asset.w, asset.h, len(asset.frames)) != (128, 96, 1):
            raise ValueError(f"{name}: expected one original 128x96 plate")
        words = asset.planar()
        if len(words) != 3072:
            raise ValueError(f"{name}: expected 6144 interleaved planar bytes")
        frames.append(words)
    return frames


def serialize(frames):
    lines = ["/* Generated by tools/make-title-plates.py; do not edit.",
             " * Original PNGs and palette preserved; no CHIP attribute or runtime allocation.",
             " * Layout: sector, row, plane, eight 16-bit words. Source SHA-256:"]
    for name in (*NAMES, "palette"):
        path = ART / (name + (".txt" if name == "palette" else ".png"))
        lines.append(f" * {path.name}: {hashlib.sha256(path.read_bytes()).hexdigest()}")
    lines += [" */", "#ifndef ASTRA_TITLE_PLATES_H", "#define ASTRA_TITLE_PLATES_H",
              "", "#include <ace/types.h>", "",
              "static const UWORD s_titlePlates[4][3072] = {"]
    for name, words in zip(NAMES, frames):
        lines.append(f"\t{{ /* {name} */")
        for offset in range(0, len(words), 8):
            lines.append("\t\t" + ", ".join(f"0x{word:04x}" for word in words[offset:offset + 8]) + ",")
        lines.append("\t},")
    return "\n".join(lines + ["};", "", "#endif", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify exact header bytes without writing")
    parser.add_argument("--compare-art", type=Path,
                        help="Verify frame zero against pre-removal generated art.c")
    args = parser.parse_args()
    frames = title_words()
    if args.compare_art:
        match = re.search(r"s_pArtGraveyard\[\]\s*=\s*\{(.*?)\};",
                          args.compare_art.read_text(), re.S)
        if not match or [int(word, 16) for word in re.findall(r"0x[0-9a-fA-F]+", match[1])] != frames[0]:
            parser.exit(1, "Graveyard does not exactly match old generated art.c\n")
        print("Graveyard: all 3072 words exactly match old generated art.c")
    path = ART / "title-plates.h"
    content = serialize(frames).encode("utf-8")
    if args.check:
        if not path.exists() or path.read_bytes() != content:
            parser.exit(1, "Stale/missing game/art/title-plates.h\n")
    else:
        path.write_bytes(content)
    print(f"{'Checked' if args.check else 'Wrote'} four original 128x96 plates: 24576 read-only bytes")


if __name__ == "__main__":
    main()
