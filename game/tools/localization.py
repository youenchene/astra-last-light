"""UTF-8 authoring catalog; generated runtime strings use explicit CP1252 bytes.

Only UI/sector text and extended 5x7 glyphs are resident. Story prose and 4x6
glyphs are baked into shared compressed rows, never copied into runtime strings.
"""
import json
from pathlib import Path

GAME = Path(__file__).resolve().parents[1]
LANGUAGES = ('fr', 'en')  # language_select.h enum order
ALPHABET = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789'
UI_KEYS = ('ASTRA LAST_LIGHT DEFEND OR CHANGE_SECTOR GAME_OVER REMEMBER RETURN_TITLE '
           'RESTART SCORE LIVES SECTOR LANCE READY DAMAGE SPEED SHIELD FIRE HOLD '
           'RELEASE BOSS PAUSE').split()


def load_catalog():
    catalog = json.loads((GAME / 'art/localization.json').read_text(encoding='utf-8'))
    assert list(catalog['ui']) == UI_KEYS, 'incomplete UI catalog'
    assert len(catalog['scenes']) == 13, 'expected thirteen scenes'
    for key, glyph in catalog['glyphs'].items():
        assert len(key.encode('cp1252')) == 1
        for name, height, maximum in (('regular', 7, 31), ('small', 6, 15)):
            assert len(glyph[name]) == height and all(0 <= n <= maximum for n in glyph[name])
    messages = []
    for pair in catalog['ui'].values():
        assert len(pair) == 2
        messages.extend(pair)
        assert all(len(encode(message, catalog)) < 32 for message in pair), 'runtime command overflow'
    for index, scene in enumerate(catalog['scenes']):
        assert scene['panel'] == index // 3 and scene['style'] == (index % 3 if index < 12 else 3)
        for language in LANGUAGES:
            assert len(scene[language]) == 3
            messages.extend(scene[language])
    for message in messages:
        encode(message, catalog)
    assert catalog['ui']['ASTRA'] == ['ASTRA'] * 2
    assert catalog['ui']['LAST_LIGHT'] == ['LAST LIGHT'] * 2
    return catalog


def encode(message, catalog):
    for letter in message:
        if letter not in ALPHABET + ' ' and letter not in catalog['glyphs']:
            raise ValueError(f'unsupported localization glyph {letter!r} in {message!r}')
    return message.encode('cp1252', errors='strict')


def c_string(message, catalog):
    # Three-digit octal escapes cannot swallow a following hexadecimal digit.
    return '"' + ''.join(chr(b) if 32 <= b < 127 else f'\\{b:03o}'
                         for b in encode(message, catalog)) + '"'


def runtime_header(catalog):
    keys = list(catalog['ui'])
    glyphs = catalog['glyphs']
    lines = ['/* Generated by make-presentation.py from localization.json. */',
             '#ifndef ASTRA_LOCALIZATION_DATA_H', '#define ASTRA_LOCALIZATION_DATA_H',
             '#include "../src/language_select.h"',
             'enum { ' + ', '.join('TEXT_' + key for key in keys) + ', TEXT_COUNT };',
             f'#define LOCALIZATION_GLYPHS {36 + len(glyphs)}',
             'static const char *const s_localizedText[2][TEXT_COUNT] = {']
    strings = set()
    for language in range(2):
        messages = [catalog['ui'][key][language] for key in keys]
        strings.update(messages)
        lines.append('\t{' + ','.join(c_string(m, catalog) for m in messages) + '},')
    lines.extend(('};', 'static const char *const s_localizedSectors[2][4] = {'))
    for language in LANGUAGES:
        messages = [catalog['scenes'][i][language][0] for i in (0, 3, 6, 9)]
        strings.update(messages)
        lines.append('\t{' + ','.join(c_string(m, catalog) for m in messages) + '},')
    lines.extend(('};', f'static const unsigned char s_extraGlyphs[{len(glyphs)}][7] = {{'))
    lines.extend('\t{' + ','.join(map(str, glyph['regular'])) + '},' for glyph in glyphs.values())
    lines.extend(('};', 'static inline const char *localizedText(unsigned char id) {',
                  '\treturn s_localizedText[languageGet()][id];', '}',
                  'static inline const char *localizedSector(unsigned char level) {',
                  '\treturn s_localizedSectors[languageGet()][level];', '}',
                  'static inline unsigned char localizedGlyph(unsigned char letter) {',
                  "\tif(letter >= 'a' && letter <= 'z') letter -= 'a' - 'A';",
                  "\tif(letter >= 'A' && letter <= 'Z') return letter - 'A';",
                  "\tif(letter >= '0' && letter <= '9') return letter - '0' + 26;",
                  "\tif(letter == ' ') return 255;", '\tswitch(letter) {'))
    for index, letter in enumerate(glyphs, 36):
        lines.append(f'\tcase {ord(letter.encode("cp1252"))}: return {index};')
    lines.extend((f'\tdefault: return {36 + list(glyphs).index("?")};', '\t}', '}', '#endif', ''))
    # 32-bit target pointers; compiler string pooling assumed, no code/alignment.
    size = sum(len(encode(s, catalog)) + 1 for s in strings) + (2 * len(keys) + 8) * 4 + len(glyphs) * 7
    return '\n'.join(lines), size
