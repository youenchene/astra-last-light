#!/usr/bin/env python3
"""Offline selected RD masters -> deduplicated sparse planar rows, ordinary data."""
import argparse
import hashlib
import json
import os
import sys
from pathlib import Path

GAME = Path(__file__).resolve().parents[1]
ART = GAME / "art/galaxy"
NAMES = ("s1-graveyard-c", "s2-nebula-b", "s3-foundry-b", "s4-citadel-a")


def quantize(path, level):
    palette = [0x001, 0x112, 0x224, 0x346]
    palette[0] = (0x001, 0x102, 0x101, 0x001)[level]
    colors = [tuple(((c >> s) & 15) * 17 for s in (8, 4, 0)) for c in palette]
    image = bytes.fromhex(path.with_suffix(".rgb.hex").read_text())
    assert len(image) == 256 * 128 * 3
    # Explicit floor-coordinate nearest neighbour, no interpolation/dithering.
    factor = 2 if level == 1 else 3
    pixels = []
    for y in range(160):
        for x in range(320):
            pos = ((y * 4 // 5) * 256 + x * 4 // 5) * 3
            rgb = tuple(v * factor // 4 for v in image[pos:pos+3])
            pixels.append(min(range(4), key=lambda i: sum((a-b)**2 for a, b in zip(rgb, colors[i]))))
    return pixels


def encode(row):
    """Only nonzero bytes: (start, count|repeat, payload), never cross a plane."""
    out = bytearray()
    pos = 0
    spans = written = 0
    while pos < len(row):
        if not row[pos]:
            pos += 1
            continue
        end = pos + 1
        while end < len(row) and row[end] == row[pos]:
            end += 1
        if end - pos >= 3:
            out.extend((pos, 128 | (end - pos), row[pos]))
            written += end - pos
            pos = end
        else:
            end = pos + 1
            while end < len(row) and row[end] and not (end + 2 < len(row) and row[end] == row[end+1] == row[end+2]):
                end += 1
            out.extend((pos, end - pos))
            out.extend(row[pos:end])
            written += end - pos
            pos = end
        spans += 1
    return spans, written, out


def generate():
    data = bytearray()
    offsets, seen = [], {}
    manifest = json.loads((ART / "manifest.json").read_text())
    for level, name in enumerate(NAMES):
        path = ART / (name + ".png")
        assert hashlib.sha256(path.read_bytes()).hexdigest() == manifest["jobs"][level]["image_sha256"]
        assert hashlib.sha256(bytes.fromhex(path.with_suffix(".rgb.hex").read_text())).hexdigest() == manifest["jobs"][level]["rgb_sha256"]
        pixels = quantize(path, level)
        assert set(pixels) <= {0, 1, 2, 3}  # Other planes are cleared, never painted.
        for y in range(160):
            spans, size = 0, 0
            encoded = bytearray()
            for plane in range(2):
                row = bytes(sum(((pixels[y*320+x*8+b] >> plane) & 1) << (7-b) for b in range(8)) for x in range(40))
                count, written, payload = encode(row)
                pos = 0
                while pos < len(payload):
                    payload[pos] |= plane << 6
                    token = payload[pos+1]
                    pos += 2 + (1 if token & 128 else token)
                encoded.extend(payload); spans += count; size += written
            assert spans + 1 <= 64 and size <= 80
            encoded = bytes((spans, size)) + encoded
            if encoded not in seen:
                seen[encoded] = len(data)
                data.extend(encoded)
            offsets.append(seen[encoded])
    assert len(data) < 65536
    def array(ctype, name, values):
        lines = [", ".join(str(v) for v in values[i:i+20]) for i in range(0, len(values), 20)]
        return f"const {ctype} {name}[] GALAXY_DATA = {{\n" + ",\n".join(lines) + "\n};\n"
    print(f"galaxy sparse payload: {len(data)} span bytes + {len(offsets)*2} index bytes")
    return "/* Generated by game/tools/make-galaxy.py; sparse rows require cleared ink-zero base. */\n#ifdef AMIGA\n#define GALAXY_DATA __attribute__((section(\".data.galaxy\")))\n#else\n#define GALAXY_DATA\n#endif\n" + array("unsigned short", "galaxyOffsets", offsets) + array("unsigned char", "galaxyBytes", data)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--import-masters", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.import_masters:
        sys.path.insert(0, str(Path(os.environ.get("AGK_KIT", Path.home() / "Code/amiga/amiga-game-kit")) / "harness"))
        from agk.image import Image
        source = args.import_masters
        provenance = json.loads((source / "manifest.json").read_text())
        ART.mkdir(exist_ok=True)
        jobs = [next(j for j in provenance["jobs"] if j["id"] == n) for n in NAMES]
        for job in jobs:
            target = ART / (job["id"] + ".png")
            target.write_bytes((source / job["image"]).read_bytes())
            image = Image.load_png(str(target))
            rgb = bytes(v for y in range(128) for x in range(256) for v in image.pixel(x,y))
            target.with_suffix(".rgb.hex").write_text(rgb.hex()+"\n")
            job["rgb_sha256"] = hashlib.sha256(rgb).hexdigest()
        (ART / "manifest.json").write_text(json.dumps({"provider": provenance["provider"], "original_batch_cost_usd": provenance["actual_cost_usd"], "additional_cost_usd": "0.00", "jobs": jobs, "derivative": "256x128 -> 320x160 floor-coordinate nearest; RGB gain 3/4 (Nebula 1/2); squared RGB distance to effective inks 0..3; no palette changes"}, indent=2) + "\n")
    result = generate()
    target = GAME / "src/galaxy_data.c"
    if args.check:
        assert target.read_text() == result, "stale galaxy data"
    else:
        target.write_text(result)
    print("galaxy data verified" if args.check else "galaxy data generated")


if __name__ == "__main__":
    main()
